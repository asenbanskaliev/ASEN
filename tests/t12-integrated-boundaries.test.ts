import test from "node:test";
import assert from "node:assert/strict";
import {execFileSync} from "node:child_process";
import {existsSync,mkdirSync,mkdtempSync,readFileSync,realpathSync,rmSync,writeFileSync} from "node:fs";
import {tmpdir} from "node:os";
import {join} from "node:path";
import {createCodeGraphTool} from "../src/interaction/code-intelligence.js";
import {prepareWorkspaceCorrection,applyWorkspaceCorrection} from "../src/runtime/workspace-resolution.js";
import {snapshotWorkspaceRoots} from "../src/runtime/workspace-snapshot.js";
import {SharedSessionDirectory} from "../src/runtime/shared-session-directory.js";
import {uninstallManaged} from "../src/runtime/managed-lifecycle.js";

test("T12 integrates read-only code research, one-use workspace correction, session consent and maintenance isolation",async t=>{
 const temporary=realpathSync.native(mkdtempSync(join(tmpdir(),"asen-t12-integrated-")));
 t.after(()=>rmSync(temporary,{recursive:true,force:true,maxRetries:20,retryDelay:100}));
 const root=join(temporary,"project");mkdirSync(root);
 const git=(...args:string[])=>execFileSync("git",["-C",root,...args],{encoding:"utf8"}).trim();
 git("init","-q");git("config","user.name","ASEN acceptance");git("config","user.email","acceptance@example.invalid");
 const source=join(root,"symbol.ts");
 writeFileSync(source,"export const trackedSymbol = 1;\n");git("add","symbol.ts");git("commit","-qm","baseline");
 const index=join(root,".codegraph"),argv:string[][]=[];
 const graph=createCodeGraphTool(async args=>{argv.push([...args]);return {stdout:"trackedSymbol",stderr:""};});
 const context={cwd:root};
 const query=await graph.execute("t12-read",{operation:"query",query:"trackedSymbol"},undefined,undefined,context as any);
 assert.equal(query.details.status,"completed");
 assert.equal(existsSync(index),false,"read-only CodeGraph queries must not initialize an index");
 assert.equal((await graph.execute("t12-init",{operation:"init"},undefined,undefined,context as any)).details.status,"authorization_required");
 assert.deepEqual(argv,[["query","--limit","10","--","trackedSymbol"]],"no unexpected index-writing commands");
 const directory=join(temporary,"shared");
 const first=new SharedSessionDirectory(directory),second=new SharedSessionDirectory(directory);
 const session={sessionId:"t12-session",subject:"Current Pi session",projectId:root,classification:"read" as const,updatedAt:new Date().toISOString()};
 first.publish(session);
 assert.deepEqual(second.list(join(temporary,"other-project")),[],"cross-project metadata must stay unavailable");
 assert.throws(()=>second.consult("forged","requester","t12-session",root),/valid unused consent/);
 const grant=second.issueConsent({requesterSessionId:"requester",targetSessionId:"t12-session",projectId:root});
 assert.equal(second.consult(grant.token,"requester","t12-session",root).sessionId,"t12-session");
 const candidate=prepareWorkspaceCorrection({root,relativePath:"symbol.ts"});
 const change=applyWorkspaceCorrection(candidate,"export const trackedSymbol = 2;\n");
 assert.equal(change.path,"symbol.ts");
 assert.equal(readFileSync(source,"utf8"),"export const trackedSymbol = 2;\n");
 assert.throws(()=>applyWorkspaceCorrection(candidate,"export const trackedSymbol = 3;\n"),/already been consumed/);
 const observed=snapshotWorkspaceRoots([root])[0]!;
 assert.equal(observed.error,undefined);
 assert.deepEqual(observed.files.map(row=>row.path),["symbol.ts"]);
 assert.equal(existsSync(index),false,"workspace correction must not implicitly change the CodeGraph index");
 const foreign=join(temporary,"foreign"),owned=join(foreign,"install");
 mkdirSync(owned,{recursive:true});
 const unrelated=join(owned,"foreign-data.txt");writeFileSync(unrelated,"preserve foreign bytes");
 await assert.rejects(()=>uninstallManaged({prefix:foreign,confirmed:true}),/ownership|foreign/i);
 assert.equal(readFileSync(unrelated,"utf8"),"preserve foreign bytes");
 first.remove("t12-session");assert.deepEqual(second.list(root),[]);
});
